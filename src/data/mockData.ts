/**
 * Map the supplied hub posters onto the demo catalogue.
 *
 * Each poster is matched to the first unused base set in the same category so
 * categories, primary asset types and demo playback keep working exactly as
 * before. The public catalogue is intentionally limited to the 13 posters we
 * actually have artwork for — no duplicated or broken images.
 */
const usedBaseSets = new Set<number>();

export const MOCK_SETS: MediaSet[] = HUB_POSTERS.map((poster, index) => {
  const baseIndex = BASE_SETS.findIndex(
    (set, setIndex) => !usedBaseSets.has(setIndex) && set.category === poster.category,
  );

  if (baseIndex === -1) {
    throw new Error(`No demo set available for poster category "${poster.category}"`);
  }

  usedBaseSets.add(baseIndex);
  const base = BASE_SETS[baseIndex];

  // Spread a representative mix of Public, Basic and Full releases through the
  // demo catalogue so entitlement behaviour can be exercised in Demo Mode.
  const access_level: MediaSet["access_level"] =
    index % 4 === 0 ? "public" : index % 3 === 0 ? "basic" : "full";

  return {
    ...base,
    slug: poster.slug,
    title: poster.title,
    description: poster.blurb,
    thumbnail_path: poster.file,
    banner_image: poster.file,
    aspect_ratio: "a4",
    genre: poster.genre,
    tags: poster.tags,
    sort_order: index + 1,
    access_level,
  };
});


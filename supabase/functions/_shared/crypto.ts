/**
 * Small, dependency-free crypto helpers shared by the OAuth functions.
 * Only Web Crypto is used so this runs unchanged in the Supabase Edge runtime.
 */

export function bytesToBase64Url(bytes: Uint8Array): string {
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/g, "");
}

export function base64UrlToBytes(value: string): Uint8Array {
  const padded = value
    .replace(/-/g, "+")
    .replace(/_/g, "/")
    .padEnd(Math.ceil(value.length / 4) * 4, "=");
  const binary = atob(padded);
  const bytes = new Uint8Array(new ArrayBuffer(binary.length));
  for (let index = 0; index < binary.length; index += 1) {
    bytes[index] = binary.charCodeAt(index);
  }
  return bytes;
}

/** Cryptographically random, URL-safe token (default 256 bits). */
export function randomToken(byteLength = 32): string {
  const buffer = new Uint8Array(new ArrayBuffer(byteLength));
  crypto.getRandomValues(buffer);
  return bytesToBase64Url(buffer);
}

/** SHA-256 as lowercase hex. Used to store only hashes of OAuth state tokens. */
export async function sha256Hex(value: string): Promise<string> {
  const digest = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(value),
  );
  return Array.from(new Uint8Array(digest))
    .map((byte) => byte.toString(16).padStart(2, "0"))
    .join("");
}
